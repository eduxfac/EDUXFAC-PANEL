CREATE TABLE perudevs_usage_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operation TEXT NOT NULL CHECK(operation IN('DNI','RUC')),
 outcome TEXT NOT NULL CHECK(outcome IN('ENCONTRADO','NO_ENCONTRADO','ERROR_API','ERROR_HTTP','ERROR_TIMEOUT')),
 created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX perudevs_usage_created_at ON perudevs_usage_events(created_at DESC);
CREATE TABLE perudevs_request_nonces (
 nonce TEXT PRIMARY KEY,
 created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX perudevs_request_nonces_created_at ON perudevs_request_nonces(created_at);
