
CREATE TABLE integration_settings(key TEXT PRIMARY KEY,value BIGINT NOT NULL);
INSERT INTO integration_settings VALUES('max_intentos',5);
CREATE TABLE integration_queue(
 id TEXT NOT NULL UNIQUE,command_id TEXT PRIMARY KEY,empresa_id TEXT NOT NULL REFERENCES web_empresas(id) DEFERRABLE INITIALLY DEFERRED,
 origen TEXT NOT NULL CHECK(origen IN('ESTADOS','COMERCIAL','SUSCRIPCIONES')),
 tipo_accion TEXT NOT NULL,payload_seguro TEXT NOT NULL CHECK(json_valid(payload_seguro)),
 estado TEXT NOT NULL CHECK(estado IN('SOLICITADO','PENDIENTE','APLICADO','ERROR','REINTENTO','CANCELADO')),
 intentos BIGINT NOT NULL DEFAULT 0,max_intentos BIGINT NOT NULL DEFAULT 5 CHECK(max_intentos BETWEEN 1 AND 20),
 retryable BIGINT NOT NULL DEFAULT 1,ultimo_error TEXT,proximo_reintento BIGINT,
 lease_owner TEXT,lease_until BIGINT,created_at TEXT NOT NULL DEFAULT panel_now(),
 updated_at TEXT NOT NULL DEFAULT panel_now(),applied_at TEXT
);
CREATE INDEX integration_queue_due ON integration_queue(estado,proximo_reintento);
CREATE TABLE integration_attempts(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,command_id TEXT NOT NULL REFERENCES integration_queue(command_id) DEFERRABLE INITIALLY DEFERRED,empresa_id TEXT NOT NULL,
 accion TEXT NOT NULL,intento BIGINT NOT NULL,estado TEXT NOT NULL,duracion_ms BIGINT NOT NULL,
 resultado TEXT NOT NULL,error TEXT,fecha TEXT NOT NULL DEFAULT panel_now(),UNIQUE(command_id,intento)
);
CREATE TABLE integration_logs(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,command_id TEXT,empresa_id TEXT,accion TEXT NOT NULL,estado TEXT NOT NULL,
 duracion_ms BIGINT NOT NULL DEFAULT 0,resultado TEXT NOT NULL,error TEXT,fecha TEXT NOT NULL DEFAULT panel_now()
);


CREATE TABLE integration_reconciliation(
 empresa_id TEXT PRIMARY KEY REFERENCES web_empresas(id) DEFERRABLE INITIALLY DEFERRED,
 estado TEXT NOT NULL CHECK(estado IN('SINCRONIZADO','DESINCRONIZADO','PENDIENTE','ERROR')),
 diferencias_json TEXT NOT NULL,local_json TEXT,web_json TEXT,ultimo_error TEXT,
 checked_at TEXT NOT NULL DEFAULT panel_now()
);
CREATE TABLE integration_health(
 id TEXT PRIMARY KEY CHECK(id='WEB'),estado TEXT NOT NULL CHECK(estado IN('ONLINE','OFFLINE','ERROR')),
 checked_ms BIGINT NOT NULL,latencia_ms BIGINT NOT NULL,ultimo_error TEXT,checked_at TEXT NOT NULL DEFAULT panel_now()
);
CREATE TABLE integration_worker_runs(
 nombre TEXT PRIMARY KEY,lease_owner TEXT,lease_until BIGINT,last_started BIGINT,last_finished BIGINT,
 resultado TEXT NOT NULL DEFAULT 'PENDIENTE'
);










CREATE OR REPLACE FUNCTION integration_capture() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE origin text;p jsonb;body jsonb;k text;
BEGIN
 origin=CASE TG_TABLE_NAME WHEN 'web_state_commands' THEN 'ESTADOS' WHEN 'web_commercial_commands' THEN 'COMERCIAL' ELSE 'SUSCRIPCIONES' END;
 IF TG_OP='INSERT' THEN
 IF origin='ESTADOS' THEN p=jsonb_build_object('command_id',NEW.command_id,'motivo',NEW.motivo,'administrador',NEW.administrador);
 ELSE body=NEW.payload_json::jsonb;p='{}'::jsonb;
 FOR k IN SELECT unnest(CASE WHEN origin='COMERCIAL' THEN ARRAY['command_id','motivo','administrador','version_condiciones','plan_codigo','limite_sucursales','limite_usuarios','multisucursal'] ELSE ARRAY['command_id','motivo','administrador','suscripcion_id','version_esperada','version_condiciones','fecha_inicio','fecha_autorizada','meses'] END)
 LOOP p=p||jsonb_build_object(k,body->k);END LOOP;
 END IF;
 INSERT INTO integration_queue(id,command_id,empresa_id,origen,tipo_accion,payload_seguro,estado,intentos,max_intentos,retryable,ultimo_error)
 VALUES(gen_random_uuid()::text,NEW.command_id,NEW.empresa_id,origin,NEW.accion,p::text,NEW.resultado,NEW.intentos,(SELECT value FROM integration_settings WHERE key='max_intentos'),NEW.retryable,NEW.error);
 ELSE
 UPDATE integration_queue SET estado=CASE WHEN estado='CANCELADO' AND NEW.resultado<>'APLICADO' THEN estado WHEN NEW.resultado='PENDIENTE' AND lease_owner IS NOT NULL AND intentos>1 THEN 'REINTENTO' ELSE NEW.resultado END,
 intentos=greatest(intentos,NEW.intentos),retryable=NEW.retryable,ultimo_error=NEW.error,
 proximo_reintento=CASE WHEN NEW.resultado IN('ERROR','APLICADO') THEN NULL ELSE proximo_reintento END,
 applied_at=CASE WHEN NEW.resultado='APLICADO' THEN coalesce(applied_at,panel_now()) ELSE applied_at END,updated_at=panel_now()
 WHERE command_id=NEW.command_id AND origen=origin;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER web_state_commands_outbox AFTER INSERT OR UPDATE OF resultado,intentos,error,retryable ON web_state_commands FOR EACH ROW EXECUTE FUNCTION integration_capture();
CREATE TRIGGER web_commercial_commands_outbox AFTER INSERT OR UPDATE OF resultado,intentos,error,retryable ON web_commercial_commands FOR EACH ROW EXECUTE FUNCTION integration_capture();
CREATE TRIGGER web_subscription_commands_outbox AFTER INSERT OR UPDATE OF resultado,intentos,error,retryable ON web_subscription_commands FOR EACH ROW EXECUTE FUNCTION integration_capture();
